  add column if not exists dodo_subscription_id text,
  add column if not exists current_period_start timestamptz,
  add column if not exists current_period_end timestamptz,
  add column if not exists cancel_at_period_end boolean not null default false,
  add column if not exists access_ends_at timestamptz,
  add column if not exists monthly_credits integer not null default 2000;

alter table public.career_entitlements
  drop constraint if exists career_entitlements_status_check;
alter table public.career_entitlements
  add constraint career_entitlements_status_check
  check (status in ('inactive','active','on_hold','cancelled','expired','revoked','refunded'));

alter table public.career_entitlements
  drop constraint if exists career_entitlements_plan_check;
alter table public.career_entitlements
  add constraint career_entitlements_plan_check
  check (plan is null or plan in ('monthly','yearly','creator','admin'));

alter table public.career_entitlements
  drop constraint if exists career_entitlements_source_check;
alter table public.career_entitlements
  add constraint career_entitlements_source_check
  check (source in ('dodo','creator','admin'));

create unique index if not exists career_entitlements_dodo_subscription_uidx
on public.career_entitlements(dodo_subscription_id)
where dodo_subscription_id is not null;

create table if not exists public.career_credit_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance integer not null default 0 check (balance >= 0),
  monthly_allowance integer not null default 2000 check (monthly_allowance >= 0),
  cycle_start timestamptz not null default now(),
  cycle_end timestamptz not null default (now() + interval '1 month'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.career_credit_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null check (event_type in ('grant','reset','debit','refund','adjustment')),
  action text not null,
  amount integer not null,
  balance_after integer not null check (balance_after >= 0),
  request_key text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists career_credit_events_request_uidx
on public.career_credit_events(user_id, request_key, event_type)
where request_key is not null;

create index if not exists career_credit_events_user_created_idx
on public.career_credit_events(user_id, created_at desc);

create table if not exists public.creator_codes (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  label text,
  duration_months integer check (duration_months is null or duration_months > 0),
  lifetime boolean not null default false,
  monthly_credits integer not null default 2000 check (monthly_credits > 0),
  expires_at timestamptz,
  max_redemptions integer not null default 1 check (max_redemptions > 0),
  redemption_count integer not null default 0 check (redemption_count >= 0),
  active boolean not null default true,
  revoked boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint creator_codes_duration_check check (lifetime or duration_months is not null)
);

create table if not exists public.creator_code_redemptions (
  id bigint generated by default as identity primary key,
  code_id uuid not null references public.creator_codes(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete cascade,
  redeemed_at timestamptz not null default now(),
  access_ends_at timestamptz,
  unique(code_id, user_id)
);

create index if not exists creator_code_redemptions_user_idx
on public.creator_code_redemptions(user_id, redeemed_at desc);

