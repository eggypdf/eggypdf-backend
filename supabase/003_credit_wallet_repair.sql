-- EggyPDF Career Pro credit-wallet repair
-- Safe to run more than once. Run AFTER 001_career_accounts.sql and 002_career_pro_billing.sql.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.career_credit_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance integer not null default 0 check (balance >= 0),
  monthly_allowance integer not null default 2000 check (monthly_allowance >= 0),
  cycle_start timestamptz not null default now(),
  cycle_end timestamptz not null default (now() + interval '1 month'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.career_credit_wallets add column if not exists balance integer not null default 0;
alter table public.career_credit_wallets add column if not exists monthly_allowance integer not null default 2000;
alter table public.career_credit_wallets add column if not exists cycle_start timestamptz not null default now();
alter table public.career_credit_wallets add column if not exists cycle_end timestamptz not null default (now() + interval '1 month');
alter table public.career_credit_wallets add column if not exists created_at timestamptz not null default now();
alter table public.career_credit_wallets add column if not exists updated_at timestamptz not null default now();

create table if not exists public.career_credit_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  action text not null,
  amount integer not null,
  balance_after integer not null,
  request_key text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.career_credit_events add column if not exists event_type text;
alter table public.career_credit_events add column if not exists action text;
alter table public.career_credit_events add column if not exists amount integer;
alter table public.career_credit_events add column if not exists balance_after integer;
alter table public.career_credit_events add column if not exists request_key text;
alter table public.career_credit_events add column if not exists metadata jsonb not null default '{}'::jsonb;
alter table public.career_credit_events add column if not exists created_at timestamptz not null default now();

create unique index if not exists career_credit_events_request_uidx
on public.career_credit_events(user_id, request_key, event_type)
where request_key is not null;

create index if not exists career_credit_events_user_created_idx
on public.career_credit_events(user_id, created_at desc);

drop trigger if exists career_credit_wallets_set_updated_at on public.career_credit_wallets;
create trigger career_credit_wallets_set_updated_at
before update on public.career_credit_wallets
for each row execute function public.set_updated_at();

alter table public.career_credit_wallets enable row level security;
alter table public.career_credit_events enable row level security;

drop policy if exists "Users can read own Career Pro wallet" on public.career_credit_wallets;
create policy "Users can read own Career Pro wallet"
on public.career_credit_wallets for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can read own Career Pro credit events" on public.career_credit_events;
create policy "Users can read own Career Pro credit events"
on public.career_credit_events for select
to authenticated
using (auth.uid() = user_id);

-- Ensure currently-active Career Pro accounts always have a wallet row.
insert into public.career_credit_wallets(
  user_id,balance,monthly_allowance,cycle_start,cycle_end
)
select
  ce.user_id,
  greatest(coalesce(ce.monthly_credits,2000),0),
  greatest(coalesce(ce.monthly_credits,2000),0),
  now(),
  now() + interval '1 month'
from public.career_entitlements ce
where ce.status='active'
  and (ce.access_ends_at is null or ce.access_ends_at > now())
on conflict (user_id) do nothing;

-- Keep allowance aligned with the entitlement without resetting already-used balance.
update public.career_credit_wallets as cw
set monthly_allowance = greatest(coalesce(ce.monthly_credits,2000),0)
from public.career_entitlements ce
where ce.user_id = cw.user_id
  and ce.status='active'
  and cw.monthly_allowance <> greatest(coalesce(ce.monthly_credits,2000),0);

create or replace function public.refresh_career_credit_cycle(p_user uuid)
returns table(balance integer, monthly_allowance integer, cycle_start timestamptz, cycle_end timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_wallet public.career_credit_wallets%rowtype;
  v_entitlement public.career_entitlements%rowtype;
  v_allowance integer;
begin
  select ce.* into v_entitlement
  from public.career_entitlements as ce
  where ce.user_id = p_user
  for update;

  if not found
     or v_entitlement.status <> 'active'
     or (v_entitlement.access_ends_at is not null and v_entitlement.access_ends_at <= now()) then
    raise exception 'Career Pro access is not active.' using errcode = 'P0001';
  end if;

  v_allowance := greatest(coalesce(v_entitlement.monthly_credits,2000),0);

  insert into public.career_credit_wallets(user_id,balance,monthly_allowance,cycle_start,cycle_end)
  values (p_user,v_allowance,v_allowance,now(),now()+interval '1 month')
  on conflict (user_id) do nothing;

  select cw.* into v_wallet
  from public.career_credit_wallets as cw
  where cw.user_id = p_user
  for update;

  if v_wallet.monthly_allowance <> v_allowance then
    update public.career_credit_wallets as cw
    set monthly_allowance = v_allowance
    where cw.user_id = p_user
    returning cw.* into v_wallet;
  end if;

  if v_wallet.cycle_end <= now() then
    update public.career_credit_wallets as cw
    set balance = cw.monthly_allowance,
        cycle_start = now(),
        cycle_end = now() + interval '1 month'
    where cw.user_id = p_user
    returning cw.* into v_wallet;

    insert into public.career_credit_events(user_id,event_type,action,amount,balance_after,metadata)
    values (
      p_user,'reset','monthly_cycle',v_wallet.monthly_allowance,v_wallet.balance,
      jsonb_build_object('cycle_end',v_wallet.cycle_end)
    );
  end if;

  return query
  select v_wallet.balance, v_wallet.monthly_allowance, v_wallet.cycle_start, v_wallet.cycle_end;
end;
$$;

create or replace function public.consume_career_credits(
  p_user uuid,
  p_amount integer,
  p_action text,
  p_request_key text
)
returns table(balance integer, charged integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_wallet public.career_credit_wallets%rowtype;
  v_prior public.career_credit_events%rowtype;
begin
  if p_amount <= 0 then
    raise exception 'Credit amount must be positive.' using errcode = '22023';
  end if;
  if coalesce(trim(p_request_key),'') = '' then
    raise exception 'A request key is required.' using errcode = '22023';
  end if;

  perform public.refresh_career_credit_cycle(p_user);

  select e.* into v_prior
  from public.career_credit_events as e
  where e.user_id=p_user
    and e.request_key=p_request_key
    and e.event_type='debit'
  limit 1;

  if found then
    return query select v_prior.balance_after,0;
    return;
  end if;

  select cw.* into v_wallet
  from public.career_credit_wallets as cw
  where cw.user_id=p_user
  for update;

  if v_wallet.balance < p_amount then
    raise exception 'Not enough Career Pro credits.' using errcode='P0001';
  end if;

  update public.career_credit_wallets as cw
  set balance = cw.balance - p_amount
  where cw.user_id=p_user
  returning cw.* into v_wallet;

  insert into public.career_credit_events(user_id,event_type,action,amount,balance_after,request_key)
  values (
    p_user,'debit',coalesce(nullif(trim(p_action),''),'ai_action'),-p_amount,
    v_wallet.balance,p_request_key
  );

  return query select v_wallet.balance,p_amount;
end;
$$;

create or replace function public.refund_career_credits(
  p_user uuid,
  p_request_key text
)
returns table(balance integer, refunded integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_debit public.career_credit_events%rowtype;
  v_refund public.career_credit_events%rowtype;
  v_wallet public.career_credit_wallets%rowtype;
  v_amount integer;
begin
  select e.* into v_debit
  from public.career_credit_events as e
  where e.user_id=p_user
    and e.request_key=p_request_key
    and e.event_type='debit'
  limit 1;

  if not found then
    return query
    select coalesce((select cw.balance from public.career_credit_wallets as cw where cw.user_id=p_user),0),0;
    return;
  end if;

  select e.* into v_refund
  from public.career_credit_events as e
  where e.user_id=p_user
    and e.request_key=p_request_key
    and e.event_type='refund'
  limit 1;

  if found then
    return query select v_refund.balance_after,0;
    return;
  end if;

  v_amount := abs(v_debit.amount);

  update public.career_credit_wallets as cw
  set balance = cw.balance + v_amount
  where cw.user_id=p_user
  returning cw.* into v_wallet;

  insert into public.career_credit_events(user_id,event_type,action,amount,balance_after,request_key,metadata)
  values (
    p_user,'refund',v_debit.action,v_amount,v_wallet.balance,p_request_key,
    jsonb_build_object('reason','failed_ai_request')
  );

  return query select v_wallet.balance,v_amount;
end;
$$;

grant execute on function public.refresh_career_credit_cycle(uuid) to service_role;
grant execute on function public.consume_career_credits(uuid,integer,text,text) to service_role;
grant execute on function public.refund_career_credits(uuid,text) to service_role;

notify pgrst, 'reload schema';
